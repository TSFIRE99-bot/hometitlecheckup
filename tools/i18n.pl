#!/usr/bin/perl
# Translation helper for HomeKeep. Runs with the Perl that comes with Git for Windows (no Python needed).
#
#   perl tools/i18n.pl extract          list every English sentence in the code -> tools/keys.txt  (id|English)
#   perl tools/i18n.pl build es so      read tools/es.txt and tools/so.txt (id|translation) and write
#                                       titlecheck/locale/es.py and so.py; stops if anything doesn't match
#
# An id is the first 8 characters of the MD5 of the English text, so it stays the same when other sentences change.
# A translation must keep the same {placeholders}, the same number of **bold** marks and the same [links](...).
use strict;
use warnings;
use utf8;
use Digest::MD5 qw(md5_hex);
use File::Find;

binmode STDOUT, ':encoding(UTF-8)';
my $root = $0 =~ m{^(.*)[/\\]tools[/\\]} ? $1 : '.';

sub unescape { my $s = shift; $s =~ s/\\(["'\\])/$1/g; return $s; }
sub id_of { my $k = shift; utf8::encode(my $b = $k); return substr(md5_hex($b), 0, 8); }

sub keys_in_code {
    my (%seen, @keys);
    my @files;
    find(sub { push @files, $File::Find::name if /\.(py|html)$/ && $File::Find::name !~ m{/(tests|locale|\.venv)/} },
         "$root/titlecheck", "$root/web");
    for my $file (sort @files) {
        open my $fh, '<:encoding(UTF-8)', $file or die "$file: $!";
        local $/; my $src = <$fh>; close $fh;
        my @found;
        if ($file =~ /\.py$/) {
            # t("..." "...") or N_("..."): one or more plain string literals in a row (never f-strings)
            while ($src =~ /\b(?:t|N_)\(\s*((?:(?:"(?:[^"\\\n]|\\.)*"|'(?:[^'\\\n]|\\.)*')\s*)+)/g) {
                my $run = $1; my $text = '';
                while ($run =~ /"((?:[^"\\\n]|\\.)*)"|'((?:[^'\\\n]|\\.)*)'/g) { $text .= unescape(defined $1 ? $1 : $2); }
                push @found, $text;
            }
        } else {
            while ($src =~ /\bt\(\s*"([^"]*)"/g) { push @found, $1; }
        }
        for my $k (@found) { next if $k eq '' || $seen{$k}++; push @keys, $k; }
    }
    return @keys;
}

sub shape {
    my $s = shift;
    my @ph = sort ($s =~ /\{(\w+)\}/g);
    my $bold = () = $s =~ /\*\*/g;
    my $links = () = $s =~ /\]\(/g;
    return join(',', @ph) . "|b$bold|l$links";
}

sub pyquote { my $s = shift; $s =~ s/\\/\\\\/g; $s =~ s/"/\\"/g; return "\"$s\""; }

my $cmd = shift @ARGV // '';
my @keys = keys_in_code();
my %by_id = map { id_of($_) => $_ } @keys;

if ($cmd eq 'extract') {
    open my $out, '>:encoding(UTF-8)', "$root/tools/keys.txt" or die $!;
    print $out id_of($_), "|", $_, "\n" for @keys;
    close $out;
    print scalar(@keys), " sentences written to tools/keys.txt\n";
}
elsif ($cmd eq 'build') {
    my $bad = 0;
    for my $lang (@ARGV) {
        open my $in, '<:encoding(UTF-8)', "$root/tools/$lang.txt" or die "tools/$lang.txt: $!";
        my %tr;
        while (my $line = <$in>) {
            $line =~ s/\r?\n$//;
            next if $line =~ /^\s*(#|$)/;
            my ($id, $text) = $line =~ /^([0-9a-f]{8})\|(.*)$/ or do { print "$lang: bad line: $line\n"; $bad++; next };
            if (!exists $by_id{$id}) { print "$lang: $id is not in the code any more\n"; next; }
            if (shape($by_id{$id}) ne shape($text)) {
                print "$lang: $id doesn't match the English ({placeholders}, ** or links):\n  EN: $by_id{$id}\n  $lang: $text\n";
                $bad++;
            }
            $tr{$by_id{$id}} = $text;
        }
        close $in;
        my @missing = grep { !exists $tr{$_} } @keys;
        print "$lang: missing ", id_of($_), "|$_\n" for @missing;
        $bad += @missing;
        my $name = $lang eq 'es' ? 'Spanish (Español)' : 'Somali (Soomaali)';
        open my $out, '>:encoding(UTF-8)', "$root/titlecheck/locale/$lang.py" or die $!;
        print $out "\"\"\"$name translations. Generated by tools/i18n.pl from tools/$lang.txt; edit that file, not this one.\"\"\"\n\n";
        print $out "T: dict[str, str] = {\n";
        print $out "    ", pyquote($_), ":\n        ", pyquote($tr{$_}), ",\n" for grep { exists $tr{$_} } @keys;
        print $out "}\n";
        close $out;
        printf "%s: %d of %d sentences translated\n", $lang, scalar(grep { exists $tr{$_} } @keys), scalar(@keys);
    }
    exit($bad ? 1 : 0);
}
else { die "usage: perl tools/i18n.pl extract | build es so\n"; }
